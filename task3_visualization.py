"""
Task 3 Prediction Visualization

Creates an example visualization showing:
    - observed trajectory before time t
    - current position at t
    - GRU predicted position at t + 1 second
    - stationary baseline prediction
    - constant-velocity baseline prediction
    - manually annotated ground-truth position at t + 1 second

This script uses the results already generated by task3_evaluation.py.
"""

import os
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt


# ============================================================
# SETTINGS
# ============================================================

DATA_DIR = "recorded_data"

RESULTS_PATH = os.path.join(
    DATA_DIR,
    "task3_evaluation_results.csv"
)

OUTPUT_PATH = os.path.join(
    DATA_DIR,
    "task3_prediction_example.png"
)

HISTORY_SECONDS = 2.0
FPS = 30.0

ARENA_SIZE_CM = 30.5


# ============================================================
# LOAD EVALUATION RESULTS
# ============================================================

results = pd.read_csv(
    RESULTS_PATH
)

print(
    f"Loaded {len(results)} evaluation points."
)


# ============================================================
# CHOOSE A REPRESENTATIVE EXAMPLE
# ============================================================

# Avoid deliberately choosing the absolute best or worst GRU example.
# Instead, choose the example whose GRU error is closest to the
# median GRU error.

median_gru_error = results[
    "gru_error_cm"
].median()

example_idx = (
    results["gru_error_cm"]
    - median_gru_error
).abs().idxmin()

example = results.loc[
    example_idx
]


# ============================================================
# GET EXAMPLE INFORMATION
# ============================================================

video_name = example[
    "video"
]

clip = os.path.splitext(
    video_name
)[0]

start_frame = int(
    example["start_frame"]
)

gt_x = example["x_GT"]
gt_y = example["y_GT"]

stationary_x = example[
    "stationary_x"
]

stationary_y = example[
    "stationary_y"
]

velocity_x = example[
    "velocity_x"
]

velocity_y = example[
    "velocity_y"
]

gru_x = example[
    "gru_x"
]

gru_y = example[
    "gru_y"
]


print()
print("Selected example:")
print(
    f"  Video: {video_name}"
)
print(
    f"  Start frame: {start_frame}"
)
print(
    f"  GRU error: "
    f"{example['gru_error_cm']:.3f} cm"
)
print(
    f"  Stationary error: "
    f"{example['stationary_error_cm']:.3f} cm"
)
print(
    f"  Constant velocity error: "
    f"{example['velocity_error_cm']:.3f} cm"
)


# ============================================================
# LOAD TRAJECTORY
# ============================================================

trajectory_path = os.path.join(
    DATA_DIR,
    f"{clip}_data_interpolated.csv"
)

trajectory = pd.read_csv(
    trajectory_path
)


# ============================================================
# FIND CURRENT FRAME
# ============================================================

matches = trajectory.index[
    trajectory["frame"]
    == start_frame
]

if len(matches) == 0:

    raise RuntimeError(
        f"Could not find frame "
        f"{start_frame} in {trajectory_path}"
    )

current_idx = matches[0]


# ============================================================
# GET PREVIOUS 2 SECONDS OF OBSERVED TRAJECTORY
# ============================================================

history_frames = int(
    round(
        HISTORY_SECONDS * FPS
    )
)

history_start_idx = max(
    0,
    current_idx
    - history_frames
    + 1
)

history = trajectory.iloc[
    history_start_idx:
    current_idx + 1
]


current_x = trajectory.iloc[
    current_idx
]["x_cm"]

current_y = trajectory.iloc[
    current_idx
]["y_cm"]


# ============================================================
# CREATE FIGURE
# ============================================================

plt.figure(
    figsize=(8, 8)
)


# ------------------------------------------------------------
# Observed trajectory
# ------------------------------------------------------------

plt.plot(
    history["x_cm"],
    history["y_cm"],
    "-",
    linewidth=2,
    label="Observed trajectory"
)


# ------------------------------------------------------------
# Current position
# ------------------------------------------------------------

plt.scatter(
    current_x,
    current_y,
    s=100,
    marker="o",
    label="Position at t",
    zorder=5
)


# ------------------------------------------------------------
# GRU prediction
# ------------------------------------------------------------

plt.plot(
    [current_x, gru_x],
    [current_y, gru_y],
    "--",
    linewidth=2
)

plt.scatter(
    gru_x,
    gru_y,
    s=130,
    marker="X",
    label="GRU prediction",
    zorder=6
)


# ------------------------------------------------------------
# Stationary baseline
#
# This will overlap the current position because stationary
# predicts that the robot remains exactly where it is.
# ------------------------------------------------------------

plt.scatter(
    stationary_x,
    stationary_y,
    s=150,
    marker="s",
    facecolors="none",
    linewidths=2,
    label="Stationary prediction",
    zorder=7
)


# ------------------------------------------------------------
# Constant velocity prediction
# ------------------------------------------------------------

plt.plot(
    [current_x, velocity_x],
    [current_y, velocity_y],
    ":",
    linewidth=2
)

plt.scatter(
    velocity_x,
    velocity_y,
    s=120,
    marker="^",
    label="Constant velocity prediction",
    zorder=6
)


# ------------------------------------------------------------
# Manual ground truth
# ------------------------------------------------------------

plt.scatter(
    gt_x,
    gt_y,
    s=180,
    marker="*",
    label="Manual ground truth at t + 1 s",
    zorder=8
)


# ------------------------------------------------------------
# Connect GRU prediction to ground truth
#
# This makes the prediction error visually obvious.
# ------------------------------------------------------------

plt.plot(
    [gru_x, gt_x],
    [gru_y, gt_y],
    "--",
    linewidth=1,
    alpha=0.6
)


# ============================================================
# FORMATTING
# ============================================================

plt.xlabel(
    "x position (cm)"
)

plt.ylabel(
    "y position (cm)"
)

plt.title(
    "Task 3: Example One-Second Motion Prediction"
)

plt.xlim(
    0,
    ARENA_SIZE_CM
)

plt.ylim(
    0,
    ARENA_SIZE_CM
)

# Keep x and y distances visually equal.
plt.gca().set_aspect(
    "equal",
    adjustable="box"
)

plt.grid(
    alpha=0.25
)

plt.legend(
    loc="best"
)

plt.tight_layout()


# ============================================================
# SAVE
# ============================================================

plt.savefig(
    OUTPUT_PATH,
    dpi=200,
    bbox_inches="tight"
)

print()
print(
    f"Saved visualization to: "
    f"{OUTPUT_PATH}"
)

plt.show()